//! Generates deep-zoom destinations (src/phenomena/mandelbrot/voyages.ts).
//!
//!   cargo run --release --example voyage_targets > ../src/phenomena/mandelbrot/voyages.ts
//!
//! Minibrots crowd around every Misiurewicz point M in rings that shrink
//! geometrically, and their periods grow only linearly with depth. So for a
//! destination of depth 10^-D we refine M, step 10^(-D/2) away from it, find
//! the lowest-period minibrot there (size ≈ 10^-D) and refine its nucleus.
//! The final view frames that minibrot inside M's spirals.

use iterum_lib::deepzoom::fexp::{CFe, Fe};
use iterum_lib::deepzoom::fixed::Fixed;
use iterum_lib::deepzoom::nucleus::{atom_size, ball_period, misiurewicz, newton_nucleus, Point};
use iterum_lib::deepzoom::reference::limbs_for_bits;

struct Recipe {
    name: &'static str,
    /// Approximate location of a Misiurewicz point.
    near: (&'static str, &'static str),
    /// Direction (radians) in which to step away from it.
    angle: f64,
    /// Target minibrot size 10^-depth.
    depth: f64,
    rate: f64,
}

const RECIPES: &[Recipe] = &[
    Recipe { name: "Seahorse Spiral", near: ("-0.77568377", "0.13646737"), angle: 0.9, depth: 40.0, rate: 0.8 },
    Recipe { name: "Dendrite Tip", near: ("0.0", "1.0"), angle: -1.2, depth: 70.0, rate: 0.9 },
    Recipe { name: "Elephant Valley", near: ("0.3013", "0.0222"), angle: 2.0, depth: 100.0, rate: 1.0 },
    Recipe { name: "Spiral Crossing", near: ("-0.1011", "0.9563"), angle: 0.4, depth: 160.0, rate: 1.1 },
    Recipe { name: "Antenna", near: ("-1.5437", "0.0"), angle: 1.3, depth: 220.0, rate: 1.2 },
    Recipe { name: "Seahorse Abyss", near: ("-0.77568377", "0.13646737"), angle: 2.6, depth: 300.0, rate: 1.4 },
    Recipe { name: "Abyssal Plain", near: ("-0.1011", "0.9563"), angle: -2.2, depth: 1000.0, rate: 2.0 },
];

fn log10(x: Fe) -> f64 {
    x.log2() * std::f64::consts::LN_2 / std::f64::consts::LN_10
}

fn locate_misiurewicz(re: &str, im: &str, limbs: usize) -> Option<(Point, u32, u32)> {
    let c0 = Point { re: Fixed::from_decimal(re, limbs).unwrap(), im: Fixed::from_decimal(im, limbs).unwrap() };
    // Prefer the simplest point near the guess.
    for total in 2..=24u32 {
        for q in 1..=total.min(8) {
            let k = total - q;
            if k == 0 {
                continue;
            }
            if let Some(m) = misiurewicz(&c0, k, q, 80) {
                let d = CFe::from_parts(m.re.sub(&c0.re).to_fe(), m.im.sub(&c0.im).to_fe()).abs().to_f64();
                if d < 2e-3 {
                    return Some((m, k, q));
                }
            }
        }
    }
    None
}

fn main() {
    println!("// Generated by src-tauri/examples/voyage_targets.rs — do not edit by hand.");
    println!("// Voyage destinations: exact nuclei of deep minibrots near Misiurewicz points.");
    println!("// depthLog2 = -log2(width of the final view in complex units).\n");
    println!("export interface VoyageTarget {{\n  name: string;\n  re: string;\n  im: string;\n  depthLog2: number;\n  /** Dive speed in octaves per second. */\n  rate?: number;\n  period?: number;\n}}\n");
    println!("export const VOYAGES: VoyageTarget[] = [");
    for r in RECIPES {
        let t0 = std::time::Instant::now();
        let Some((m, k, q)) = locate_misiurewicz(r.near.0, r.near.1, limbs_for_bits(256)) else {
            eprintln!("{}: no Misiurewicz point near the guess", r.name);
            continue;
        };
        let bits = (r.depth * 3.33 * 1.15) as u32 + 160;
        let l = limbs_for_bits(bits);
        let m = misiurewicz(&m.resized(l), k, q, 200).expect("refines at high precision");
        let d = Fe::from_log2(-r.depth * 0.5 * std::f64::consts::LOG2_10);
        let dir = CFe::new(r.angle.cos(), r.angle.sin(), 0);
        let c = m.offset(dir.mul(CFe::from_parts(d, Fe::ZERO)));
        let Some(p) = ball_period(&c, d.mul(Fe::from_f64(0.5)), 2_000_000) else {
            eprintln!("{}: no minibrot found", r.name);
            continue;
        };
        let Some(n) = newton_nucleus(&c, p, 400) else {
            eprintln!("{}: nucleus did not converge (period {p})", r.name);
            continue;
        };
        let size = atom_size(&n, p);
        let depth = -log10(size.abs());
        eprintln!(
            "{}: M({k},{q}) period {p} size 1e-{depth:.1} bits {bits} ({:.1}s)",
            r.name,
            t0.elapsed().as_secs_f64()
        );
        let digits = (depth + 12.0) as usize;
        let depth_log2 = -(size.abs().log2() + 12f64.log2());
        println!(
            "  {{ name: \"{}\", re: \"{}\", im: \"{}\", depthLog2: {:.2}, rate: {}, period: {} }},",
            r.name,
            n.re.to_decimal(digits),
            n.im.to_decimal(digits),
            depth_log2,
            r.rate,
            p
        );
    }
    println!("];");
}
